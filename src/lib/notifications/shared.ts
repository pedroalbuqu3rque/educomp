import { z } from "zod";

export type NotificationKind =
 | "material_submitted" | "review_pending" | "material_in_review"
 | "material_approved" | "material_rejected" | "material_changes_requested" | "material_published"
 | "material_unpublished" | "new_material" | "comment_reply"
 | "material_comment" | "moderation" | "report_resolved" | "announcement";

export type NotificationItem = {
 id: string;
 kind: NotificationKind;
 title: string;
 body: string;
 targetUrl: string;
 createdAt: string;
 readAt: string | null;
};

export type NotificationPageData = {
 items: NotificationItem[];
 unread: number;
 total: number;
 page: number;
 pages: number;
};

export const notificationActionSchema = z.discriminatedUnion("action", [
 z.object({ action: z.literal("read"), id: z.string().uuid() }).strict(),
 z.object({ action: z.literal("unread"), id: z.string().uuid() }).strict(),
 z.object({ action: z.literal("read_all") }).strict(),
]);

// Notifications are generated by the database, but never trust a URL before navigation.
export function safeNotificationPath(path: unknown): string {
 if (typeof path !== "string" || path.length > 300 || !path.startsWith("/") || path.startsWith("//")
  || /[\\\r\n\u0000-\u001f]/.test(path)) return "/biblioteca";
 return path;
}

export function notificationCategory(kind: NotificationKind): string {
 switch (kind) {
  case "new_material": return "Novo material";
  case "review_pending": return "Revisão";
  case "material_submitted": case "material_in_review": case "material_approved":
  case "material_rejected": case "material_changes_requested": case "material_published": case "material_unpublished": return "Meus envios";
  case "comment_reply": case "material_comment": return "Comunidade";
  case "moderation": case "report_resolved": return "Moderação";
  case "announcement": return "Atualização";
 }
}

export function notificationDate(value: string, now = new Date()): string {
 const date = new Date(value);
 if (!Number.isFinite(date.getTime())) return "Data indisponível";
 const difference = now.getTime() - date.getTime();
 const minutes = Math.floor(difference / 60_000);
 if (minutes >= 0 && minutes < 1) return "Agora";
 if (minutes >= 1 && minutes < 60) return `Há ${minutes} ${minutes===1?"minuto":"minutos"}`;
 const hours = Math.floor(minutes/60);
 if (hours >= 1 && hours < 24) return `Há ${hours} ${hours===1?"hora":"horas"}`;
 const days = Math.floor(hours/24);
 if (days === 1) return "Ontem";
 if (days >= 2 && days <= 6) return `Há ${days} dias`;
 return new Intl.DateTimeFormat("pt-BR", {
  day: "2-digit", month: "short", year: "numeric", timeZone: "America/Sao_Paulo",
 }).format(date);
}
